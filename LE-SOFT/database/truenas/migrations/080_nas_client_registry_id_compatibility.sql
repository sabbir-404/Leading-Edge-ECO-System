-- Keep NAS and Supabase schemas compatible for clients selecting
-- nas_client_registry.id while retaining installation_id as the primary key.
BEGIN;

ALTER TABLE public.nas_client_registry
    ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE UNIQUE INDEX IF NOT EXISTS nas_client_registry_id_compatibility_uidx
    ON public.nas_client_registry (id);

NOTIFY pgrst, 'reload schema';
COMMIT;
