-- The live PostgREST clients still select nas_client_registry.id. Preserve the
-- installation_id primary key while adding a stable, generated compatibility
-- identifier. This is additive and does not change existing lease identity.
BEGIN;

ALTER TABLE public.nas_client_registry
    ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE UNIQUE INDEX IF NOT EXISTS nas_client_registry_id_compatibility_uidx
    ON public.nas_client_registry (id);

NOTIFY pgrst, 'reload schema';
COMMIT;
